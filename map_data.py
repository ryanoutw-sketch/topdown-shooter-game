def spawn_where(map_id, team):
    """出生位置的說明文字，例如 "top"、"left"。"""
    return MAPS.get(map_id, MAPS[DEFAULT_MAP]).get("where", {}).get(team, "")


def solid_rects(m):
    """地圖上所有實心掩體（箱子 + 物件）的矩形。"""
    return list(m.get("crates", [])) + [p[1:] for p in m.get("props", [])]
