DEFAULT_MAP = "dunes"


def _curve(pts, width=3):
    """沿著一串路徑點，每格放一個 width x width 的方塊 → 彎曲的巷子。"""
    half = width // 2
    out = []
    for (x1, y1), (x2, y2) in zip(pts, pts[1:]):
        n = max(abs(x2 - x1), abs(y2 - y1))
        for k in range(n):
            cx, cy = round(x1 + (x2 - x1) * k / n), round(y1 + (y2 - y1) * k / n)
            out.append((cx - half, cy - half, width, width))
    x, y = pts[-1]
    return out + [(x - half, y - half, width, width)]


